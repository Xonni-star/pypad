# Lektion 01 — Beispiel: Ausgaben & Variablen
# Ausführen: Knopf unten links (oder Cmd+Enter)

# 1) Eine Variable ist ein Name für einen Wert.
name = "Max"
alter = 21
hobby = "Python lernen"

# 2) print() gibt aus. Mehrere Dinge mit Komma -> Leerzeichen dazwischen.
print("Hallo", name)

# 3) f-string: Werte mitten im Text. Das kleine f macht { } zu Platzhaltern.
print(f"Ich bin {alter} Jahre alt.")
print(f"Mein Hobby: {hobby}")

# 4) Zeichen wiederholen: "-" * 30 ergibt eine Trennlinie.
print("-" * 30)

# 5) Mit Zahlen kann man rechnen, mit Text nicht.
print(f"In 10 Jahren bin ich {alter + 10}.")
print("-" * 30)
print("Fertig!")
