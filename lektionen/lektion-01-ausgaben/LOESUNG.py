# Der Trick ist der f-string: das kleine f vor dem Anführungszeichen macht {name}
# zu einem Platzhalter, der beim Ausgeben durch den Wert ersetzt wird.

name = "Max"
alter = 21
wohnort = "Berlin"

print(f"Ich heiße {name}, bin {alter} Jahre alt und wohne in {wohnort}.")
print("-" * 25)          # Zeichen wiederholen ergibt die Trennlinie
